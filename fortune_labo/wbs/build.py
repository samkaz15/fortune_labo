DEP_RE = __import__("re").compile(r"^([0-9.]+G?)(?:\((FS|SS)\))?$")


def validate() -> list[str]:
    """依存の存在と日付整合を検査する。

    依存は既定で FS（先行完了 → 後続開始）。並行開始してよいものは
    `0.5.1(SS)` のように SS を明記する。SS を書かずに日付が逆転していれば
    それは計画の誤りなので、ここで落とす。
    """
    rows = rows_as_dicts()
    by_id = {r["WBS番号"]: r for r in rows}
    problems = []
    for r in rows:
        for token in (t.strip() for t in r["依存"].split(",")):
            if token in ("", "-"):
                continue
            m = DEP_RE.match(token)
            if not m:
                problems.append(f'{r["WBS番号"]}: 依存の書式が不正 "{token}"')
                continue
            dep_id, kind = m.group(1), (m.group(2) or "FS")
            dep = by_id.get(dep_id)
            if dep is None:
                problems.append(f'{r["WBS番号"]}: 存在しない依存 "{dep_id}"')
                continue
            if kind == "FS" and r["開始日"] and dep["期限"] and r["開始日"] < dep["期限"]:
                problems.append(
                    f'{r["WBS番号"]}({r["開始日"]}) が FS依存 {dep_id}(期限 {dep["期限"]}) '
                    f"より早く開始している。並行開始が正しいなら {dep_id}(SS) と書く"
                )
    for r in rows:
        if r["開始日"] and r["期限"] and r["開始日"] > r["期限"]:
            problems.append(f'{r["WBS番号"]}: 開始日が期限より後')
    return problems


def main(argv: list[str]) -> int:
    problems = validate()
    if problems:
        print(f"WBS検証エラー {len(problems)}件:")
        for p in problems:
            print(f"  - {p}")
        return 1

    targets = {HERE / "wbs-master.csv": render_csv(), HERE / "wbs-master.md": render_md()}
    if "--check" in argv:
        stale = [p.name for p, want in targets.items()
                 if not p.exists() or p.read_text() != want]
        if stale:
            print("stale (run `python3 build.py`): " + ", ".join(stale))
            return 1
        print("up to date")
        return 0
    for path, content in targets.items():
        path.write_text(content)
        print(f"wrote {path.name} ({len(content.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
