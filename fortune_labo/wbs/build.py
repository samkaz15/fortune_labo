def rows_as_dicts() -> list[dict]:
    out = []
    for r in ROWS:
        wbs, phase, task, definition, depends, output, owner, level, start, end, days = r
        out.append({
            "WBS番号": wbs, "フェーズ": phase, "タスク": task, "定義": definition,
            "依存": depends, "アウトプット": output, "担当": owner, "自動化レベル": level,
            "開始日": start, "期限": end, "日数": days, "進捗": "0%",
        })
    return out


def render_csv() -> str:
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows_as_dicts())
    return buf.getvalue()


